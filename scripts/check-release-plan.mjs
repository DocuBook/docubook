#!/usr/bin/env node
/**
 * Release-plan regression guard for `.changeset/config.json`.
 *
 * Runs the read-only Changesets planner (`changeset status --output`) against
 * isolated fixture changesets and asserts the resulting package/bump matrix, so
 * a configuration change that reintroduces the linked-group escalation reported
 * in DocuBook/docubook#403 fails here instead of at publish time.
 *
 * Version numbers are deliberately not asserted: the linked group advances, and
 * `applyLinks` aligns `oldVersion` to the highest version in the group. Only
 * package names and bump types are compared.
 *
 * Read-only: this never runs `changeset version` or `changeset publish`. One
 * fixture is written to `.changeset/release-plan-check.md` for the duration of
 * the run and removed afterwards, so do not run it alongside `version-packages`.
 *
 * `changeset status` resolves the base branch from `.changeset/config.json`
 * (`main`), so that ref has to exist in the local clone.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const cli = path.join(root, "node_modules", "@changesets", "cli", "bin.js");
const fixture = path.join(root, ".changeset", "release-plan-check.md");
const scratch = mkdtempSync(path.join(tmpdir(), "docubook-release-plan-"));
const planFile = path.join(scratch, "plan.json");

/**
 * Each scenario writes a single-package fixture and compares the planner output
 * with the expected `[package, bumpType]` pairs.
 */
const scenarios = [
  {
    pkg: "@docubook/core",
    bump: "patch",
    expected: [["@docubook/core", "patch"]],
  },
  {
    // Regression guard for #403: a core minor must not escalate the group.
    pkg: "@docubook/core",
    bump: "minor",
    expected: [["@docubook/core", "minor"]],
  },
  {
    // Every dependent range is left, so the cascade is the expected behaviour.
    pkg: "@docubook/core",
    bump: "major",
    expected: [
      ["@docubook/core", "major"],
      ["@docubook/flame", "major"],
      ["@docubook/markdown", "major"],
    ],
  },
  {
    pkg: "@docubook/flame",
    bump: "patch",
    expected: [["@docubook/flame", "patch"]],
  },
  {
    pkg: "@docubook/markdown",
    bump: "patch",
    expected: [["@docubook/markdown", "patch"]],
  },
  {
    pkg: "@docubook/ui-react",
    bump: "minor",
    expected: [["@docubook/ui-react", "minor"]],
  },
];

const removeFixture = () => rmSync(fixture, { force: true });
const cleanup = () => {
  removeFixture();
  rmSync(scratch, { recursive: true, force: true });
};

process.on("SIGINT", () => {
  cleanup();
  process.exit(130);
});
process.on("SIGTERM", () => {
  cleanup();
  process.exit(143);
});

const byName = (a, b) => a[0].localeCompare(b[0]);
const format = (pairs) =>
  pairs.map(([name, type]) => `${name}:${type}`).join(", ") || "(no releases)";

const readPlan = () => {
  const plan = JSON.parse(readFileSync(planFile, "utf8"));
  if (!Array.isArray(plan.releases)) {
    throw new Error(`unexpected planner output in ${planFile}`);
  }
  return plan.releases.map((release) => [release.name, release.type]).sort(byName);
};

let failures = 0;
console.log("release-plan check (.changeset/config.json)");

try {
  for (const { pkg, bump, expected } of scenarios) {
    const label = `${pkg}: ${bump}`;
    if (existsSync(fixture)) {
      throw new Error(
        `${path.relative(root, fixture)} already exists; remove it and re-run ` +
          "(a previous run was likely interrupted)"
      );
    }

    writeFileSync(
      fixture,
      `---\n"${pkg}": ${bump}\n---\n\nGenerated by scripts/check-release-plan.mjs.\n`
    );

    try {
      execFileSync(process.execPath, [cli, "status", `--output=${planFile}`], {
        cwd: root,
        stdio: ["ignore", "pipe", "pipe"],
      });

      const actual = readPlan();
      if (JSON.stringify(actual) === JSON.stringify([...expected].sort(byName))) {
        console.log(`  ok   ${label.padEnd(24)} ${format(actual)}`);
      } else {
        failures += 1;
        console.log(`  FAIL ${label.padEnd(24)} expected ${format(expected)}`);
        console.log(`       ${" ".repeat(24)} actual   ${format(actual)}`);
      }
    } catch (error) {
      failures += 1;
      console.log(`  FAIL ${label.padEnd(24)} planner error`);
      console.log(String(error.stderr ?? error.message).trim());
    } finally {
      removeFixture();
    }
  }
} finally {
  cleanup();
}

if (failures > 0) {
  console.error(`\nrelease-plan check failed: ${failures} of ${scenarios.length} scenarios`);
  process.exit(1);
}

console.log(`\nrelease-plan check passed: ${scenarios.length} scenarios`);
